#!/usr/bin/env python3
"""Single Android/Mac colour source. Run with --check in verification."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
palette = json.loads((root / 'code/shared/colours.json').read_text())
colours = {k: v for k, v in palette.items() if isinstance(v, dict)}
kotlin = ['// Generated by code/shared/generate-colours.py; do not edit.',
          'package dev.syncr.prototype.ui.theme', '', 'object NotePalette {']
for name, modes in colours.items():
    kotlin.append(f'    fun {name}(dark: Boolean): Int = if (dark) 0x{modes["dark"]}.toInt() else 0x{modes["light"]}.toInt()')
kotlin += [f'    const val highlighterAlpha: Int = 0x{palette["highlighter_alpha"]}', '}']
swift = ['// Generated by code/shared/generate-colours.py; do not edit.',
         'import SyncrCore', '', 'enum NotePalette {']
for name, modes in colours.items():
    swift.append(f'    static func {name}(_ dark: Bool) -> UInt32 {{ dark ? 0x{modes["dark"]} : 0x{modes["light"]} }}')
swift += [f'    static let highlighterAlpha: UInt32 = 0x{palette["highlighter_alpha"]}',
          '    static func rgba(_ argb: UInt32) -> SIMD4<Float> {',
          '        SIMD4(Float((argb >> 16) & 255), Float((argb >> 8) & 255), Float(argb & 255), Float(argb >> 24)) / 255',
          '    }',
          '    static func colour(_ colour: InkColour, dark: Bool, highlighter: Bool) -> SIMD4<Float> {',
          '        let rgb: UInt32', '        switch colour {']
for name in ['ink', 'red', 'green', 'blue', 'orange']:
    swift.append(f'        case .{name}: rgb = {name}(dark)')
swift += ['        }',
          '        return rgba(highlighter ? (rgb & 0x00ffffff) | (highlighterAlpha << 24) : rgb)',
          '    }', '}']
outputs = {
    'code/android/app/src/main/java/dev/syncr/prototype/ui/theme/NotePalette.kt': '\n'.join(kotlin) + '\n',
    'code/mac/Sources/SyncrMac/NotePalette.swift': '\n'.join(swift) + '\n',
}
for path, text in outputs.items():
    target = root / path
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != text:
            sys.exit(f'Stale generated colour table: {path}')
    else:
        target.write_text(text)
print('Shared colours: OK')
