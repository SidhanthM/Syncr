#!/usr/bin/env python3
"""Single Android/Mac colour source, plus the Mac window tokens. Run with --check in verification."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
palette = json.loads((root / 'code/shared/colours.json').read_text())
colours = {k: v for k, v in palette.items() if isinstance(v, dict)}
kotlin = ['// Generated by code/shared/generate-colours.py; do not edit.',
          'package dev.syncr.prototype.ui.theme', '', 'object NotePalette {']
for name, modes in colours.items():
    kotlin.append(f'    fun {name}(dark: Boolean): Int = if (dark) 0x{modes["dark"]}.toInt() else 0x{modes["light"]}.toInt()')
kotlin += [f'    const val highlighterAlpha: Int = 0x{palette["highlighter_alpha"]}', '}']
swift = ['// Generated by code/shared/generate-colours.py; do not edit.',
         'import SyncrCore', '', 'enum NotePalette {']
for name, modes in colours.items():
    swift.append(f'    static func {name}(_ dark: Bool) -> UInt32 {{ dark ? 0x{modes["dark"]} : 0x{modes["light"]} }}')
swift += [f'    static let highlighterAlpha: UInt32 = 0x{palette["highlighter_alpha"]}',
          '    static func rgba(_ argb: UInt32) -> SIMD4<Float> {',
          '        SIMD4(Float((argb >> 16) & 255), Float((argb >> 8) & 255), Float(argb & 255), Float(argb >> 24)) / 255',
          '    }',
          '    static func colour(_ colour: InkColour, dark: Bool, highlighter: Bool) -> SIMD4<Float> {',
          '        let rgb: UInt32', '        switch colour {']
for name in ['ink', 'red', 'green', 'blue', 'orange']:
    swift.append(f'        case .{name}: rgb = {name}(dark)')
swift += ['        }',
          '        return rgba(highlighter ? (rgb & 0x00ffffff) | (highlighterAlpha << 24) : rgb)',
          '    }', '}']
theme = {k: v for k, v in json.loads((root / 'code/shared/mac-theme.json').read_text()).items() if isinstance(v, dict)}
def camel(name): return name.split('_')[0] + ''.join(w.title() for w in name.split('_')[1:])
tokens = ['// Generated by code/shared/generate-colours.py from mac-theme.json; do not edit.', '',
          '/// Mac window colours (ARGB). Pen colours are in `NotePalette`.', 'enum ThemeTokens {']
for name, modes in theme.items():
    tokens.append(f'    static func {camel(name)}(_ dark: Bool) -> UInt32 {{ dark ? 0x{modes["dark"]} : 0x{modes["light"]} }}')
tokens.append('}')

# Syntax colours for fenced code, one table for both platforms.
code = {k: v for k, v in json.loads((root / 'code/shared/code-colours.json').read_text()).items() if isinstance(v, dict)}
def luminance(argb):
    def lin(c): c /= 255; return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin((argb >> 16) & 255) + 0.7152 * lin((argb >> 8) & 255) + 0.0722 * lin(argb & 255)
def over(fg, bg, a):
    return sum(round(a * ((fg >> s) & 255) + (1 - a) * ((bg >> s) & 255)) << s for s in (16, 8, 0))
def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True); return (hi + 0.05) / (lo + 0.05)
for mode in ('light', 'dark'):
    ink, page = int(theme['ink'][mode], 16), int(theme['page'][mode], 16)
    paper = int(palette['paper'][mode], 16)
    # The page, the phone's paper and the code fill (ink at 12%) over each.
    grounds = [page, paper, over(ink, page, 0.12), over(ink, paper, 0.12)]
    for name, modes in code.items():
        for g in grounds:
            ratio = contrast(int(modes[mode], 16), g)
            if ratio < 4.5: sys.exit(f'Code colour {name} ({mode}) is {ratio:.2f}:1 on {g:06x}, below 4.5')
groups = {'keyword': ['Keyword'], 'string': ['String'], 'comment': ['Comment'], 'number': ['Number', 'Constant'],
          'function': ['Function'], 'type': ['Type', 'Tag'], 'attribute': ['Attribute'], 'plain': ['Variable', 'Operator', 'Punctuation']}
code_swift = ['// Generated by code/shared/generate-colours.py from code-colours.json; do not edit.', 'import SyncrCore', '',
              '/// Syntax colours for fenced code (ARGB), the same hex values as the phone.', 'enum CodeColours {']
code_kotlin = ['// Generated by code/shared/generate-colours.py from code-colours.json; do not edit.',
               'package dev.syncr.prototype.ui.theme', '', 'import dev.syncr.core.CodeToken', '',
               '/** Syntax colours for fenced code (ARGB), the same hex values as the Mac. */', 'object CodeColours {']
for name, modes in code.items():
    code_swift.append(f'    static func {name}(_ dark: Bool) -> UInt32 {{ dark ? 0x{modes["dark"]} : 0x{modes["light"]} }}')
    code_kotlin.append(f'    fun {name}(dark: Boolean): Int = if (dark) 0x{modes["dark"]}.toInt() else 0x{modes["light"]}.toInt()')
code_swift += ['    static func colour(_ token: CodeToken, _ dark: Bool) -> UInt32 {', '        switch token {']
code_kotlin += ['    fun colour(token: CodeToken, dark: Boolean): Int = when (token) {']
for name, tokens_ in groups.items():
    code_swift.append('        case ' + ', '.join('.' + t.lower() if t != 'String' else '.string' for t in tokens_) + f': return {name}(dark)')
    code_kotlin.append('        ' + ', '.join('CodeToken.' + t.upper() for t in tokens_) + f' -> {name}(dark)')
code_swift += ['        }', '    }', '    static func isItalic(_ token: CodeToken) -> Bool { token == .comment }', '}']
code_kotlin += ['    }', '    fun isItalic(token: CodeToken): Boolean = token == CodeToken.COMMENT', '}']
outputs = {
    'code/mac/Sources/SyncrMac/CodeColours.swift': '\n'.join(code_swift) + '\n',
    'code/android/app/src/main/java/dev/syncr/prototype/ui/theme/CodeColours.kt': '\n'.join(code_kotlin) + '\n',
    'code/android/app/src/main/java/dev/syncr/prototype/ui/theme/NotePalette.kt': '\n'.join(kotlin) + '\n',
    'code/mac/Sources/SyncrMac/NotePalette.swift': '\n'.join(swift) + '\n',
    'code/mac/Sources/SyncrMac/ThemeTokens.swift': '\n'.join(tokens) + '\n',
}
for path, text in outputs.items():
    target = root / path
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != text:
            sys.exit(f'Stale generated colour table: {path}')
    else:
        target.write_text(text)
print('Shared colours: OK')
