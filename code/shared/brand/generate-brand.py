#!/usr/bin/env python3
"""Syncr brand generator: the dot-matrix wordmark and the "S" app icon, from one source.

Letters are hand-drawn bitmaps on a strict grid (5 x 7 cells, one-cell strokes, one empty column between
letters), every "on" cell a full round dot on a uniform pitch. The only "dither" is deliberate: the last
letter's arm dissolves to the right into smaller, sparser dots that end in the single salmon dot, echoing
the stipple dissolve. Dot size (halftone) may fade slightly left to right; dots are never removed from
inside a stroke. Palette: bone, ink, one salmon dot.

Run: python3 code/shared/brand/generate-brand.py [--no-icns]
Writes: Android drawables, the Mac wordmark table and Syncr.icns, and PNG/SVG previews in this folder.
"""
import os, subprocess, sys, shutil, tempfile
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
RES = os.path.join(ROOT, "code/android/app/src/main/res")
MAC = os.path.join(ROOT, "code/mac")

BONE, INK, SALMON, NIGHT, BONE_INK = "#FBFBFA", "#1E1E1E", "#D39999", "#141414", "#F0EFEA"

# ---- glyphs: 5 wide, x-height 5 rows, caps 7 rows; "y" has a 2-row descender (7 rows from the x-height top) ----
GLYPHS = {
    "S": [".###.",
          "#...#",
          "#....",
          ".###.",
          "....#",
          "#...#",
          ".###."],
    "y": ["#...#",
          "#...#",
          "#...#",
          ".####",
          "....#",
          "#...#",
          ".###."],
    "n": ["#.##.",
          "##..#",
          "#...#",
          "#...#",
          "#...#"],
    "c": [".###.",
          "#...#",
          "#....",
          "#...#",
          ".###."],
    "r": ["#.##.",
          "##..#",
          "#....",
          "#....",
          "#...."],
}
CAP_ROWS, ROWS = 7, 9          # lowercase sits on the cap baseline (row 6); y descends to row 8
GAP = 1                        # empty columns between letters
R_FULL, R_FADE = 0.45, 0.38    # dot radius in cells: left edge, right edge (a slight halftone fade)
TRAIL_R = (0.33, 0.25, 0.18)   # the dissolve after the r's arm, then the salmon dot at full size


def wordmark():
    """Returns (cols, rows, ink dots [(x, y, r)], salmon (x, y, r))."""
    cells, x = [], 0
    for ch in "Syncr":
        g = GLYPHS[ch]
        top = CAP_ROWS - len(g) if ch not in "y" else 2     # lowercase letters sit on the baseline; y is 7 tall from row 2
        if ch == "S":
            top = 0
        for j, row in enumerate(g):
            for i, v in enumerate(row):
                if v == "#":
                    cells.append((x + i, top + j))
        x += 5 + GAP
    last = max(c[0] for c in cells)                          # right edge of the r's arm
    width = last
    ink = [(cx, cy, R_FULL - (R_FULL - R_FADE) * cx / width) for cx, cy in cells]
    arm_row = 3                                              # the shoulder of the r: the row it dissolves along
    ink += [(last + 1 + k, arm_row, r) for k, r in enumerate(TRAIL_R)]
    salmon = (last + 1 + len(TRAIL_R), arm_row, R_FULL)
    return salmon[0] + 1, ROWS, ink, salmon


# ---- the S icon: 7 x 9 cells, one-cell stroke, the salmon dot is the top-right terminal ----
ICON_S = [".#####.",
          "#.....#",
          "#......",
          "#......",
          ".#####.",
          "......#",
          "......#",
          "#.....#",
          ".#####."]
ICON_R = 0.4
ICON_SALMON = (6, 1)


def icon_s():
    ink = [(i, j) for j, row in enumerate(ICON_S) for i, v in enumerate(row) if v == "#" and (i, j) != ICON_SALMON]
    return len(ICON_S[0]), len(ICON_S), ink, ICON_SALMON


# ---- writers ----
def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z"


def vector(name, w, h, vw, vh, layers, comment):
    body = "\n".join(f'    <path\n        android:fillColor="{col}"\n        android:pathData="{d}" />' for col, d in layers if d)
    out = (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by code/shared/brand/generate-brand.py; do not edit. -->\n'
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="{w}dp"\n    android:height="{h}dp"\n'
           f'    android:viewportWidth="{vw}"\n    android:viewportHeight="{vh}">\n{body}\n</vector>\n')
    open(os.path.join(RES, "drawable", name), "w").write(out)


def write_android(wm, icon):
    cols, rows, dots, sal = wm
    ink = "".join(circle(x + .5, y + .5, r) for x, y, r in dots)
    dot = circle(sal[0] + .5, sal[1] + .5, sal[2])
    w, h = f"{cols * 2.7:.1f}", f"{rows * 2.7:.1f}"
    vector("syncr_wordmark.xml", w, h, cols, rows, [("@color/syncr_ink", ink), ("@color/syncr_accent", dot)],
           "The Syncr wordmark: dot-matrix letters, the r dissolving into one salmon dot.")
    # The app has its own light/dark switch, so the phone header tints the ink layer itself and stacks the dot on top.
    vector("syncr_wordmark_ink.xml", w, h, cols, rows, [("#FF000000", ink)], "The wordmark's ink dots in one colour, tinted in code.")
    vector("syncr_wordmark_dot.xml", w, h, cols, rows, [(SALMON, dot)], "The wordmark's salmon dot, same viewport as the ink layer.")
    icols, irows, idots, isal = icon
    pitch = 6.2
    ox, oy = (108 - icols * pitch) / 2, (108 - irows * pitch) / 2

    def d(cells):
        return "".join(circle(ox + (x + .5) * pitch, oy + (y + .5) * pitch, ICON_R * pitch) for x, y in cells)
    vector("ic_launcher_foreground.xml", 108, 108, 108, 108, [(INK, d(idots)), (SALMON, d([isal]))],
           "Launcher foreground: a dot-matrix S, its top-right end one salmon dot. 108dp canvas, inside the 66dp safe circle.")
    vector("ic_launcher_monochrome.xml", 108, 108, 108, 108, [("#FF000000", d(idots + [isal]))],
           "Themed-icon layer: the same dots in one colour; the launcher tints it.")
    vector("ic_splash.xml", 108, 108, 108, 108, [("@color/syncr_ink", d(idots)), ("@color/syncr_accent", d([isal]))],
           "Splash icon: the launcher S in the page's ink so it shows in light and dark.")


def write_mac_table(wm):
    cols, rows, dots, sal = wm
    flat = ", ".join(f"{x},{y},{round(r * 100)}" for x, y, r in dots)
    open(os.path.join(MAC, "Sources/SyncrMac/BrandWordmarkData.swift"), "w").write(
        "// Generated by code/shared/brand/generate-brand.py; do not edit.\n"
        f"enum BrandWordmarkData {{\n    static let columns = {cols}, rows = {rows}\n"
        f"    static let accent = (x: {sal[0]}, y: {sal[1]}, r: {round(sal[2] * 100)})\n"
        f"    /// Ink dots as x, y, radius-in-hundredths-of-a-cell triples.\n    static let dots: [Int] = [{flat}]\n}}\n")


def colours(dark):
    return (BONE_INK, NIGHT) if dark else (INK, BONE)


def svg_wordmark(wm, dark):
    cols, rows, dots, sal = wm
    p, pad = 10, 3
    ink, bg = colours(dark)
    w, h = (cols + 2 * pad) * p, (rows + 2 * pad) * p
    body = "".join(f'<circle cx="{(x + pad + .5) * p}" cy="{(y + pad + .5) * p}" r="{r * p:.2f}" fill="{ink}"/>' for x, y, r in dots)
    body += f'<circle cx="{(sal[0] + pad + .5) * p}" cy="{(sal[1] + pad + .5) * p}" r="{sal[2] * p:.2f}" fill="{SALMON}"/>'
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><rect width="{w}" height="{h}" fill="{bg}"/>{body}</svg>\n'


def png_wordmark(wm, dark, name):
    cols, rows, dots, sal = wm
    p, pad, k = 16, 4, 3
    ink, bg = colours(dark)
    W, H = (cols + 2 * pad) * p, (rows + 2 * pad) * p
    im = Image.new("RGB", (W * k, H * k), bg)
    d = ImageDraw.Draw(im)
    for x, y, r in dots + [(sal[0], sal[1], sal[2])]:
        cx, cy, rr = (x + pad + .5) * p * k, (y + pad + .5) * p * k, r * p * k
        d.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=SALMON if (x, y) == sal[:2] else ink)
    im.resize((W, H), Image.LANCZOS).save(os.path.join(HERE, name))


# ---- Mac icon: macOS grid, 824 px body on a 1024 canvas, soft shadow ----
def mac_icon(icon, dark):
    cols, rows, dots, sal = icon
    N, k = 2048, 2
    base = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    body = [100 * k, 100 * k, 924 * k, 924 * k]
    shadow = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).rounded_rectangle([body[0], body[1] + 12 * k, body[2], body[3] + 12 * k], radius=185 * k, fill=(0, 0, 0, 90))
    base.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(14 * k)))
    d = ImageDraw.Draw(base)
    d.rounded_rectangle(body, radius=185 * k, fill=NIGHT if dark else BONE)
    pitch = 62 * k                                    # S body is 9 x 62 = 558 px, about 55% of the canvas
    ox, oy = (N - cols * pitch) / 2, (N - rows * pitch) / 2
    ink = BONE_INK if dark else INK
    for x, y in dots + [sal]:
        cx, cy, r = ox + (x + .5) * pitch, oy + (y + .5) * pitch, ICON_R * pitch
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=SALMON if (x, y) == sal else ink)
    return base.resize((1024, 1024), Image.LANCZOS)


def write_mac(icon, icns):
    light, dark = mac_icon(icon, False), mac_icon(icon, True)
    light.save(os.path.join(HERE, "icon-1024.png"))
    dark.save(os.path.join(HERE, "icon-dark-1024.png"))
    if not icns:
        return
    if not shutil.which("iconutil"):
        print("iconutil not found; skipping Syncr.icns")
        return
    tmp = tempfile.mkdtemp()
    iconset = os.path.join(tmp, "Syncr.iconset")
    os.makedirs(iconset)
    for s in (16, 32, 128, 256, 512):
        light.resize((s, s), Image.LANCZOS).save(os.path.join(iconset, f"icon_{s}x{s}.png"))
        light.resize((s * 2, s * 2), Image.LANCZOS).save(os.path.join(iconset, f"icon_{s}x{s}@2x.png"))
    os.makedirs(os.path.join(MAC, "Resources"), exist_ok=True)
    subprocess.run(["iconutil", "-c", "icns", iconset, "-o", os.path.join(MAC, "Resources/Syncr.icns")], check=True)
    shutil.rmtree(tmp)


def previews():
    """The icon at 48/96/512 on one sheet, light above dark."""
    light, dark = Image.open(os.path.join(HERE, "icon-1024.png")), Image.open(os.path.join(HERE, "icon-dark-1024.png"))
    sizes = (48, 96, 512)
    sheet = Image.new("RGB", (sum(sizes) + 40 * (len(sizes) + 1), 512 * 2 + 120), "#E9E7E2")
    for row, ic in enumerate((light, dark)):
        x = 40
        for s in sizes:
            t = ic.resize((s, s), Image.LANCZOS)
            sheet.paste(t, (x, 40 + row * (512 + 40) + (512 - s) // 2), t)
            x += s + 40
    sheet.save(os.path.join(HERE, "icon-preview.png"))


def main():
    wm, icon = wordmark(), icon_s()
    write_android(wm, icon)
    write_mac_table(wm)
    for dark in (False, True):
        tag = "dark" if dark else "light"
        png_wordmark(wm, dark, f"wordmark-{tag}.png")
        open(os.path.join(HERE, f"wordmark-{tag}.svg"), "w").write(svg_wordmark(wm, dark))
    write_mac(icon, "--no-icns" not in sys.argv)
    previews()
    print(f"wordmark {wm[0]}x{wm[1]} cells, {len(wm[2])} dots; icon S {icon[0]}x{icon[1]} cells, {len(icon[2]) + 1} dots")


if __name__ == "__main__":
    main()
